const CARON = '.#.#.|..#..';
const ACUTE = '...#.|..#..';
const COMPOSED: Record<string, [string, string]> = { Č: ['C', CARON], Ć: ['C', ACUTE], Š: ['S', CARON], Ž: ['Z', CARON] };

export const FONT_CHARS = Object.keys(G).join('') + Object.keys(COMPOSED).join('');
export const FONT_CELL_W = 6;
export const FONT_CELL_H = 10;
export const FONT_PER_ROW = 16;

/** Returns the glyph as 10 rows of 5 chars (accent rows + body), or null. */
export function glyphRows(ch: string): string[] {
  const comp = COMPOSED[ch];
  if (comp) return [...comp[1].split('|'), ...G[comp[0]].split('|')];
  const g = G[ch] ?? G['?'];
  return ['.....', '.....', ...g.split('|')];
}

export function buildFontCanvas(): HTMLCanvasElement {
  const chars = [...FONT_CHARS];
  const rows = Math.ceil(chars.length / FONT_PER_ROW);
  const cv = document.createElement('canvas');
  cv.width = FONT_PER_ROW * FONT_CELL_W;
  cv.height = rows * FONT_CELL_H;
  const ctx = cv.getContext('2d')!;
  chars.forEach((ch, i) => {
    const ox = (i % FONT_PER_ROW) * FONT_CELL_W;
    const oy = Math.floor(i / FONT_PER_ROW) * FONT_CELL_H;
    const g = glyphRows(ch);
    for (const [dx, dy, col] of [[1, 1, '#1a1420'], [0, 0, '#ffffff']] as const) {
      ctx.fillStyle = col;
      g.forEach((row, y) => { for (let x = 0; x < 5; x++) if (row[x] === '#') ctx.fillRect(ox + x + dx, oy + y + dy, 1, 1); });
    }
  });
  return cv;
}

/** Uppercases and replaces characters the font lacks. */
export function normalizeText(s: string): string {
  const up = s.toUpperCase();
  let out = '';
  for (const ch of up) out += ch === '\n' || FONT_CHARS.includes(ch) ? ch : '?';
  return out;
}
